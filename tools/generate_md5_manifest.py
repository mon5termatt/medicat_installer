#!/usr/bin/env python3
"""Generate a MedicatFiles.md5-style manifest by hashing every file under a folder.

Example:
  python tools/generate_md5_manifest.py ^
    --root F:\\MEDICAT2026\\26.12 ^
    --out F:\\MEDICAT2026\\26.12\\MedicatFiles.md5

  python tools/generate_md5_manifest.py ^
    --root F:\\MEDICAT2026\\26.12 ^
    --bootables ^
    --out F:\\MEDICAT2026\\MedicatFiles.26.12.bootables.md5
"""

from __future__ import annotations

import argparse
import hashlib
import os
import sys
import time
from concurrent.futures import ThreadPoolExecutor, as_completed
from pathlib import Path


BOOTABLES_IGNORED_TOP_DIRS = ("portableapps", "programs")


def normalize_rel(path: str) -> str:
    text = path.replace("\\", "/").strip()
    while text.startswith("./"):
        text = text[2:]
    return text.lstrip("/")


def is_bootables_ignored_path(rel: str) -> bool:
    top = normalize_rel(rel).split("/", 1)[0].lower() if rel else ""
    return top in BOOTABLES_IGNORED_TOP_DIRS


def walk_files(root: Path, *, bootables: bool) -> list[tuple[str, Path]]:
    files: list[tuple[str, Path]] = []
    for dirpath, dirs, names in os.walk(root):
        current = Path(dirpath)
        if bootables and current.resolve() == root.resolve():
            dirs[:] = [name for name in dirs if name.lower() not in BOOTABLES_IGNORED_TOP_DIRS]
        for name in names:
            full = current / name
            rel = normalize_rel(str(full.relative_to(root)))
            if not rel:
                continue
            if bootables and is_bootables_ignored_path(rel):
                continue
            # Never include a previously generated manifest sitting in the tree.
            if rel.lower() in {"medicatfiles.md5", "medicatupdate.md5"}:
                continue
            files.append((rel, full))
    files.sort(key=lambda item: item[0].lower())
    return files


def md5_file(path: Path) -> str:
    hasher = hashlib.md5()
    with path.open("rb") as handle:
        while True:
            chunk = handle.read(1024 * 1024)
            if not chunk:
                break
            hasher.update(chunk)
    return hasher.hexdigest()


def hash_one(item: tuple[str, Path]) -> tuple[str, str]:
    rel, full = item
    return rel, md5_file(full)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--root", type=Path, required=True, help="Folder to hash (USB-relative tree root)")
    parser.add_argument("--out", type=Path, required=True, help="Output .md5 path")
    parser.add_argument(
        "--bootables",
        action="store_true",
        help="Ignore top-level PortableApps/ and Programs/",
    )
    parser.add_argument(
        "--workers",
        type=int,
        default=max(4, min(16, (os.cpu_count() or 4))),
        help="Parallel hash workers (default: CPU-based)",
    )
    args = parser.parse_args()

    root = args.root.resolve()
    if not root.is_dir():
        print(f"Root not found: {root}", file=sys.stderr)
        return 1

    def log(message: str) -> None:
        print(message, flush=True)

    log(f"Scanning {root} ...")
    files = walk_files(root, bootables=bool(args.bootables))
    if not files:
        print("No files found to hash", file=sys.stderr)
        return 1
    log(f"Hashing {len(files)} files with {args.workers} workers ...")

    t0 = time.perf_counter()
    results: dict[str, str] = {}
    done = 0
    with ThreadPoolExecutor(max_workers=max(1, args.workers)) as pool:
        futures = [pool.submit(hash_one, item) for item in files]
        for future in as_completed(futures):
            rel, digest = future.result()
            results[rel] = digest
            done += 1
            if done == 1 or done == len(files) or done % 25 == 0:
                elapsed = time.perf_counter() - t0
                rate = done / elapsed if elapsed > 0 else 0.0
                log(f"  {done}/{len(files)} ({rate:.1f} files/s) last={rel}")

    lines = [f"{results[rel]} *{rel}" for rel, _full in files]

    lines.sort(key=lambda line: line.split("*", 1)[-1].lower())
    out = args.out.resolve()
    out.parent.mkdir(parents=True, exist_ok=True)
    header = (
        f"; Generated by generate_md5_manifest.py\n"
        f"; Root: {root}\n"
        f"; Files: {len(lines)}\n"
        f"; bootables_only: {bool(args.bootables)}\n"
        f";\n"
    )
    out.write_text(header + "\n".join(lines) + "\n", encoding="utf-8")
    elapsed = time.perf_counter() - t0
    print(f"Wrote {out} ({len(lines)} entries, {elapsed:.1f}s)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
